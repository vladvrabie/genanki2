#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["anki"]
# ///
"""The collection schema Anki produces, dumped as a reference snapshot.

    uv run scripts/dump_anki_schema.py

Creates a throwaway collection with the official `anki` package, reads its
`sqlite_master` and writes the DDL to src/genanki2/_schema.py.

Output is deterministic for a given Anki version. Re-running it after an Anki
upgrade can produce a diff: no diff means the schema is unchanged, a diff is the
list of things genanki2 needs to update.
"""

import sqlite3
import sys
import tempfile
from pathlib import Path

import anki.buildinfo
from anki.collection import Collection


def dump_schema(db: sqlite3.Connection) -> str:
  """Render `db`'s schema as the `_schema.py` module source."""
  schema_version: int = db.execute("SELECT ver FROM col").fetchone()[0]
  rows: list[tuple[str]] = db.execute(
    "SELECT sql "
    "FROM sqlite_master "
    "WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' "
    # Put tables first, then indexes and anything else
    "ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END, name"
  ).fetchall()
  lines: list[str] = [
    "# Generated by scripts/dump_anki_schema.py, do not edit.",
    f"# anki {anki.buildinfo.version}, collection schema version {schema_version}",
    "",
    'SCHEMA = """',
  ]
  lines += [f"{sql.strip()};\n" for (sql,) in rows]
  lines += [
    '"""',
    "",
  ]
  return "\n".join(lines)


def main() -> int:
  """Create a throwaway collection, dump its schema, and write `_schema.py`."""
  with tempfile.TemporaryDirectory() as tmp:
    path: Path = Path(tmp) / "collection.anki2"
    col: Collection = Collection(str(path))
    col.close()
    db: sqlite3.Connection = sqlite3.connect(path)
    pycontent: str = dump_schema(db)
    db.close()

  project_path: Path = Path(__file__).resolve().parent.parent
  pyfile: Path = project_path / "src" / "genanki2" / "_schema.py"
  pyfile.parent.mkdir(parents=True, exist_ok=True)
  changed: bool = not pyfile.exists() or pyfile.read_text() != pycontent
  pyfile.write_text(pycontent)
  print(f"{'updated' if changed else 'unchanged'}: {pyfile}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
