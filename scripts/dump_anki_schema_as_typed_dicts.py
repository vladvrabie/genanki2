#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["anki"]
# ///
"""The collection schema Anki produces, dumped as `TypedDict` row types.

    uv run scripts/dump_anki_schema_as_typed_dicts.py

Creates a throwaway collection with the official `anki` package, reads each table
through `PRAGMA table_info` and writes src/genanki2/_typed_schema.py: one `TypedDict`
per table with a field per column, followed by a `Sequence` alias per row type.

A class is named after its table, title-cased with the underscores removed and a
trailing `s` dropped, so `deck_config` yields `DeckConfigRow` and `DeckConfigRows`.

A field's type comes from the type the DDL declares for the column: `text` to `str`,
`integer` and `boolean` to `int`, `blob` to `bytes`. Two exceptions:
  - `notes.sfld` is declared `integer` so that a sort field holding a number sorts
    numerically, but what it stores is text.
  - `tags.config` is the schema's only nullable column, so `bytes | None`.

Output is deterministic for a given Anki version. Re-running it after an Anki
upgrade can produce a diff: no diff means the schema is unchanged, a diff is the
list of things genanki2 needs to update.
"""

import sqlite3
import sys
import tempfile
from pathlib import Path
from typing import Any

import anki.buildinfo
from anki.collection import Collection

AFFINITY_TO_PYTHON: dict[str, str] = {
  "TEXT": "str",
  "NUMERIC": "float",
  "INTEGER": "int",
  "REAL": "float",
  "BOOLEAN": "int",
  "BLOB": "bytes",
}

SPECIAL_CASES = {
  ("notes", "sfld"): "str",
  ("tags", "config"): "bytes | None",
}


def read_table_names(db: sqlite3.Connection) -> list[str]:
  """List every user table in `db`, skipping SQLite's own."""
  query: str = (
    "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
  )
  return [row[0] for row in db.execute(query).fetchall()]


def read_table_column_types(db: sqlite3.Connection) -> dict[str, list[tuple[str, str]]]:
  """Return the column names and types for each table in `db`."""
  table_columns: dict[str, list[tuple[str, str]]] = {}
  for table in read_table_names(db):
    column_infos: list[Any] = db.execute(f"PRAGMA table_info({table})").fetchall()
    # Column info: (cid, name, type, notnull, default_value, pk)
    table_columns[table] = [
      (column_info[1], column_info[2].upper()) for column_info in column_infos
    ]
  return table_columns


def dump_typed_dicts(db: sqlite3.Connection) -> str:
  """Write module source by rendering `db`'s tables as `TypedDict`s."""
  schema_version: int = db.execute("SELECT ver FROM col").fetchone()[0]
  lines: list[str] = [
    "# Generated by scripts/dump_anki_schema_as_typed_dicts.py, do not edit.",
    f"# anki {anki.buildinfo.version}, collection schema version {schema_version}",
    "",
    "from collections.abc import Sequence",
    "from typing import TypeAlias",
    "",
    "from typing_extensions import TypedDict",  # Pydantic refuses typing.TypedDict for Python <3.12
  ]

  class_names: list[str] = []
  for table, columns in read_table_column_types(db).items():
    class_names.append(f"{table.title().rstrip('s').replace('_', '')}Row")
    lines.append(f"\n\nclass {class_names[-1]}(TypedDict):")
    for column, column_type in columns:
      column_type = SPECIAL_CASES.get((table, column), AFFINITY_TO_PYTHON[column_type])
      lines.append(f"  {column}: {column_type}")

  lines.append("\n")
  for name in class_names:
    lines.append(f"{name}s: TypeAlias = Sequence[{name}]")
  lines.append("")
  return "\n".join(lines)


def main() -> int:
  """Create a throwaway collection, read its columns and write `_typed_schema.py`."""
  with tempfile.TemporaryDirectory() as tmp:
    path: Path = Path(tmp) / "collection.anki2"
    col: Collection = Collection(str(path))
    col.close()
    db: sqlite3.Connection = sqlite3.connect(path)
    pycontent: str = dump_typed_dicts(db)
    db.close()

  project_path: Path = Path(__file__).resolve().parent.parent
  pyfile: Path = project_path / "src" / "genanki2" / "_typed_schema.py"
  pyfile.parent.mkdir(parents=True, exist_ok=True)
  changed: bool = not pyfile.exists() or pyfile.read_text() != pycontent
  pyfile.write_text(pycontent)
  print(f"{'updated' if changed else 'unchanged'}: {pyfile}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
