#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# ///
"""The codepoints Anki does not know are assigned, dumped as regex character classes.

    uv run scripts/dump_unicode_ages.py [--anki-unicode MAJOR.MINOR]

Fetches `DerivedAge.txt`, the UCD file recording which Unicode version assigned each
codepoint and writes src/genanki2/_unicode_ages.py: one regex per version above Anki's,
plus `RE_ASSIGNED_AFTER_ANKIS_UNICODE` covering all of them.

`--anki-unicode` is the Unicode version Anki checks media names against, 10.0 by
default. Anki takes it from the `unic-ucd-category` crate (0.9.0 carries Unicode 10.0),
so rerun the script with the crate's version whenever Anki's `Cargo.toml` bumps it.

The URL tracks the latest UCD release, so the table grows as Unicode does. The first
line of the fetched file names the revision and goes into the generated header.
"""

import argparse
import itertools
import sys
from collections.abc import Iterable
from pathlib import Path
from typing import TypeAlias
from urllib.request import urlopen

Version: TypeAlias = tuple[int, int]
CodepointRange: TypeAlias = tuple[int, int]
AgesDict: TypeAlias = dict[Version, list[CodepointRange]]


UNICODE_AGES_URL: str = "https://www.unicode.org/Public/UCD/latest/ucd/DerivedAge.txt"
ANKI_UNICODE_VERSION: Version = (10, 0)


def retrieve_url(url: str) -> str:
  """Read the document at `url` as text."""
  with urlopen(url) as response:
    return response.read().decode()


def parse_version(string: str) -> Version:
  """Parse a version, `"11.0"` into `(11, 0)` and `"11"` into `(11, 0)`."""
  major, _, minor = string.strip().partition(".")
  return int(major), int(minor or 0)


def parse_version_arg(string: str) -> Version:
  """Parse the `--anki-unicode` value, rejecting text that is not a version."""
  try:
    return parse_version(string)
  except ValueError:
    raise argparse.ArgumentTypeError(
      f"{string!r} is not a MAJOR.MINOR version"
    ) from None


def parse_codepoints(string: str) -> CodepointRange:
  """Parse a `DerivedAge.txt` codepoint field into an inclusive range.

  - XXXX..YYYY -> (XXXX, YYYY)
  - ZZZZ -> (ZZZZ, ZZZZ)
  """
  string = string.strip().lower()
  if ".." in string:
    start, end_inclusive = string.split("..", 1)
    return int(start, 16), int(end_inclusive, 16)
  start = int(string, 16)
  return start, start


def parse_ages_file(file: str) -> AgesDict:
  """Group the codepoint ranges in `file` by the version that assigned them."""
  ages: AgesDict = {}
  for line in file.split("\n"):
    line = line.strip()
    if not line or line[0] == "#":
      continue
    codepoints_str, rest = line.split(";", 1)
    version_str, _ = rest.split("#", 1)
    version: Version = parse_version(version_str)
    cp_range: CodepointRange = parse_codepoints(codepoints_str)
    ages.setdefault(version, []).append(cp_range)
  return ages


def merge_codepoint_ranges(ranges: Iterable[CodepointRange]) -> list[CodepointRange]:
  """Merge contiguous ranges: `(1, 3)` and `(4, 9)` become `(1, 9)`."""
  ranges = sorted(ranges)
  if not ranges:
    return []
  merged: list[CodepointRange] = ranges[:1]
  for next_start, next_end_incl in ranges[1:]:
    last_start, last_end_incl = merged[-1]
    if last_end_incl + 1 == next_start:
      merged[-1] = last_start, next_end_incl
    else:
      merged.append((next_start, next_end_incl))
  return merged


def to_unicode_escape(codepoint: int) -> str:
  r"""Format `codepoint` as a `\uXXXX` or `\UXXXXXXXX` regex escape."""
  if codepoint < 0x10000:
    return f"\\u{codepoint:04x}"
  else:
    return f"\\U{codepoint:08x}"


def make_regex_str(ranges: Iterable[CodepointRange]) -> str:
  """Build a character class matching every codepoint in `ranges`.

  Examples: `"[<char>]"`, `"[<char1-char2>]"`

  Empty input gives an empty pattern (`"[]"` does not compile).
  """
  re_pattern: str = ""
  for start, end_incl in ranges:
    if start == end_incl:
      re_pattern += to_unicode_escape(start)
    else:
      re_pattern += f"{to_unicode_escape(start)}-{to_unicode_escape(end_incl)}"
  return f"[{re_pattern}]" if re_pattern else ""


def dump_unicode_ages(provenance: str, ages: AgesDict, anki_version: Version) -> str:
  """Render the generated module, `provenance` naming the UCD revision it came from.

  One compiled character class per age, then one more covering all.
  """
  lines: list[str] = [
    "# Generated by scripts/dump_unicode_ages.py, do not edit.",
    f"{provenance}",
    "import re",
    "",
    f"ANKI_UNICODE_VERSION: tuple[int, int] = {anki_version}",
    "",
  ]

  # One regex for each Unicode version
  for (major, minor), ranges in ages.items():
    re_var: str = f"RE_UNICODE_{major}_{minor}_ASSIGNED: re.Pattern[str] = re.compile("
    re_line: str = f'  r"{make_regex_str(ranges)}"'
    lines.extend([re_var, re_line, ")\n"])

  # A regex with all after Anki's version
  re_var = "RE_ASSIGNED_AFTER_ANKIS_UNICODE: re.Pattern[str] = re.compile("
  all_merged: list[CodepointRange] = merge_codepoint_ranges(
    itertools.chain.from_iterable(ages.values())
  )
  re_line = f'  r"{make_regex_str(all_merged)}"'
  lines.extend([re_var, re_line, ")\n"])

  return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
  """Fetch the UCD file, keep the versions above Anki's, write `_unicode_ages.py`."""
  parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])  # pyright: ignore[reportOptionalMemberAccess]
  parser.add_argument(
    "--anki-unicode",
    type=parse_version_arg,
    default=ANKI_UNICODE_VERSION,
    metavar="MAJOR.MINOR",
    help="the Unicode version of Anki's unic-ucd-category crate (default: 10.0)",
  )
  anki_version: Version = parser.parse_args(argv).anki_unicode

  ages_file: str = retrieve_url(UNICODE_AGES_URL)
  provenance: str = ages_file[: ages_file.index("#\n")]
  ages: AgesDict = parse_ages_file(ages_file)
  if anki_version not in ages:
    known: str = ", ".join(f"{major}.{minor}" for major, minor in sorted(ages))
    parser.error(f"Unicode {anki_version[0]}.{anki_version[1]} does not exist: {known}")
  ages = {
    version: merge_codepoint_ranges(ranges)
    for version, ranges in ages.items()
    if version > anki_version
  }
  pycontent: str = dump_unicode_ages(provenance, ages, anki_version)

  project_path: Path = Path(__file__).resolve().parent.parent
  pyfile: Path = project_path / "src" / "genanki2" / "_unicode_ages.py"
  pyfile.parent.mkdir(parents=True, exist_ok=True)
  changed: bool = not pyfile.exists() or pyfile.read_text() != pycontent
  pyfile.write_text(pycontent)
  print(f"{'updated' if changed else 'unchanged'}: {pyfile}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
