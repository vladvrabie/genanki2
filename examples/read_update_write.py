"""Update a deck: read last time's package, change it, write it again.

    python examples/read_update_write.py italian.apkg italian-v2.apkg

This script uses the package generated by examples/language_deck.py.

The identifiers are read from the file, so this script needs no constants: the notetype
keeps its id, each note its guid, each deck its name. Importing the new package updates
the notes that the users already have.

In Anki, an import only adds and updates. A note removed from a package (like in this
script) stays in the collection of every user who imported an earlier version of the
package containing it.
"""

import sys
from pathlib import Path

from genanki2 import Genanki2Error, Package, guid_for, note


def synthesize(text: str, path: Path) -> Path:
  """Stand in for a TTS engine writing an mp3."""
  path.write_bytes(f"audio for {text}".encode())
  return path


def main(source: Path, target: Path) -> None:
  # The media files stay in the source package until the write copies them.
  pkg = Package.read_apkg(source, keep_source_media=True)
  collection = pkg.collection

  vocabulary = collection.get_deck(name="Italian::Vocabulary")
  if vocabulary is None:
    raise Genanki2Error('Could not find deck "Italian::Vocabulary"')
  word = collection.get_notetype(name="Italian word")
  if word is None:
    raise Genanki2Error('Could not find notetype "Italian word"')
  by_word = {
    note_["Italian"]: note_
    for note_ in collection.notes
    if note_.notetype.id == word.id
  }

  # Correct a translation. The guid is unchanged, so the import updates the note.
  by_word["casa"]["English"] = "house, home"

  # Audio that was missing last time. The note's listening template is no longer
  # empty, so it gains that card, at the note's existing new-card position.
  mp3_path = synthesize("rapidamente", target.parent / "it_rapidamente.mp3")
  pkg.media.append(str(mp3_path))
  by_word["rapidamente"]["Audio"] = f"[sound:{mp3_path.name}]"
  collection.generate_missing_cards()

  # A new word, studied after every word already in the deck.
  guid = guid_for(word.id, "finestra")
  new_word = note(word, ["finestra", "window", ""], tags=["noun"], guid=guid)
  collection.add_notes([new_word], vocabulary)

  # A word dropped from the deck takes its cards, their reviews and its audio along.
  collection.remove_notes([by_word["mangiare"]])
  pkg.trim_unused_media()

  pkg.write_apkg(target)


if __name__ == "__main__":
  main(Path(sys.argv[1]), Path(sys.argv[2]))
